
from pathlib import Path


def generate_code_skeleton(project_name, design_result):
    """Generate a basic Python project skeleton."""

    if not project_name or not project_name.strip():
        raise ValueError("Project name cannot be empty.")

    if design_result.get("status") != "completed":
        raise ValueError("Valid design output is required.")

    safe_name = "".join(
        char.lower() if char.isalnum() else "_"
        for char in project_name.strip()
    ).strip("_")

    if not safe_name:
        raise ValueError("Project name must contain letters or numbers.")

    generated_files = {
        "main.py": '''def main():
    print("Application started successfully.")
    print("Generated by SDLC Factory.")


if __name__ == "__main__":
    main()
''',
        "app.py": '''class Application:
    """Main application class."""

    def run(self):
        return {
            "status": "success",
            "message": "Application executed successfully."
        }
''',
        "config.py": '''APP_NAME = "Generated Application"
APP_VERSION = "1.0.0"
DEBUG = True
''',
        "README.md": f'''# {project_name}

## Overview
This project was generated using the SDLC Factory.

## Architecture
{design_result.get("architecture", "Not specified")}

## Execution
Run the application using:

```bash
python main.py
```
'''
    }

    return {
        "agent": "Code Generation Agent",
        "status": "completed",
        "project_name": project_name,
        "project_folder": safe_name,
        "generated_files": generated_files,
        "file_count": len(generated_files)
    }


def save_generated_code(code_result, output_directory):
    """Save generated source files to the output directory."""

    project_folder = (
        Path(output_directory)
        / code_result["project_folder"]
    )

    project_folder.mkdir(parents=True, exist_ok=True)

    for filename, content in code_result["generated_files"].items():
        file_path = project_folder / filename
        file_path.write_text(content, encoding="utf-8")

    return str(project_folder)
